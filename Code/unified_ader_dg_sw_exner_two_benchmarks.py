def dg_one_stage_update(modal: torch.Tensor, Uc: torch.Tensor, Fc: torch.Tensor, Sc: torch.Tensor,
                        dx: float, dt: float, return_fluxes: bool = False):
    """Equation (7): volume + source + time-integrated interface fluxes."""
    N, _, kp1 = modal.shape
    k = kp1 - 1

    xi, wx = gauss_legendre(NQ_SPACE)
    theta, wt = gauss_legendre(NQ_TIME, 0.0, 1.0)
    P = legendre_values(k, xi)
    dP = legendre_derivative_values(k, xi)
    Pminus, Pplus = legendre_at_endpoints(k)

    # Volume/source integrals.
    vol = torch.zeros((N, 3, k + 1), dtype=DTYPE, device=DEVICE)
    src = torch.zeros_like(vol)
    for it in range(theta.numel()):
        tloc = dt * theta[it]
        for ix in range(xi.numel()):
            z = 0.5 * dx * xi[ix]
            Fq = eval_series(Fc, z, tloc, k)
            Sq = eval_series(Sc, z, tloc, k)
            weight = dt * wt[it] * wx[ix]
            for ell in range(k + 1):
                # dx/2 * d/dx(P_l) = d/dxi(P_l)
                vol[:, :, ell] += weight * Fq * dP[ell, ix]
                src[:, :, ell] += weight * (0.5 * dx) * Sq * P[ell, ix]

    # Time-integrated interface fluxes.
    Fhat_for_left_cell = torch.zeros((N + 1, 3), dtype=DTYPE, device=DEVICE)
    Fhat_for_right_cell = torch.zeros_like(Fhat_for_left_cell)
    for it in range(theta.numel()):
        tloc = dt * theta[it]
        cell_left, cell_right = predictor_interface_states(Uc, dx, tloc)
        UL, UR = all_interface_states(cell_left, cell_right)
        FL, FR = interface_prebalanced_flux(UL, UR)
        Fhat_for_left_cell += dt * wt[it] * FL
        Fhat_for_right_cell += dt * wt[it] * FR

    new = torch.empty_like(modal)
    for ell in range(k + 1):
        M = dx / float(2 * ell + 1)
        rhs = M * modal[:, :, ell] + vol[:, :, ell] + src[:, :, ell]
        # right interface index j+1 uses left-cell corrected flux;
        # left interface index j uses right-cell corrected flux.
        rhs -= Fhat_for_left_cell[1:] * Pplus[ell]
        rhs += Fhat_for_right_cell[:-1] * Pminus[ell]
        new[:, :, ell] = rhs / M
    if return_fluxes:
        return new, Fhat_for_left_cell, Fhat_for_right_cell
    return new


def minmod3(a: torch.Tensor, b: torch.Tensor, c: torch.Tensor) -> torch.Tensor:
    same = ((a > 0) & (b > 0) & (c > 0)) | ((a < 0) & (b < 0) & (c < 0))
    mag = torch.minimum(torch.abs(a), torch.minimum(torch.abs(b), torch.abs(c)))
    return torch.where(same, torch.sign(a) * mag, torch.zeros_like(a))


def _dilate_mask(mask: torch.Tensor, radius: int) -> torch.Tensor:
    """Dilate a 1D Boolean cell mask by `radius` neighboring cells."""
    if radius <= 0 or not torch.any(mask):
        return mask
    out = mask.clone()
    for _ in range(radius):
        left = torch.cat((out[:1], out[:-1]))
        right = torch.cat((out[1:], out[-1:]))
        out = out | left | right
    return out


def detect_troubled_cells(modal: torch.Tensor, dx: float):
    """
    TVB/DMP troubled-cell detector in the variables requested by the user:
        (eta, q, b).

    A cell is mildly troubled if the P2 polynomial leaves the local range of
    neighboring CELL AVERAGES by more than M_TVB*dx^2. A bathymetry violation
    is classified as strong, because the sharp Exner shock is precisely where
    the old post-limiter left oscillatory cell averages. Strong cells are
    expanded by FV_FALLBACK_BUFFER cells so that the discontinuity is enclosed
    in a small robust FV patch.
    """
    if modal.shape[-1] <= 1 or not USE_TROUBLED_CELL_LIMITER:
        z = torch.zeros(modal.shape[0], dtype=torch.bool, device=DEVICE)
        return z, z, torch.zeros((modal.shape[0], 3), dtype=torch.bool, device=DEVICE)

    xi_check = torch.tensor(
        [-1.0, -0.75, -0.5, 0.0, 0.5, 0.75, 1.0],
        dtype=DTYPE,
        device=DEVICE,
    )
    vals = evaluate_modal(modal, xi_check)  # (N,3,nq), variables eta,q,b
    avg = modal[:, :, 0]

    avg_pad = torch.cat((avg[:1], avg, avg[-1:]), dim=0)
    lo = torch.minimum(avg_pad[:-2], torch.minimum(avg_pad[1:-1], avg_pad[2:]))
    hi = torch.maximum(avg_pad[:-2], torch.maximum(avg_pad[1:-1], avg_pad[2:]))

    tol = TVB_M * dx * dx
    comp_troubled = torch.any(
        (vals < (lo[:, :, None] - tol)) | (vals > (hi[:, :, None] + tol)),
        dim=2,
    )  # (N,3): eta,q,b

    troubled = torch.any(comp_troubled, dim=1)

    # Use FV fallback only around a genuinely sharp morphodynamic jump.
    # The previous version classified every small b-DMP violation as strong,
    # which was robust but unnecessarily diffusive in eta and q. Here the
    # strong sensor is based on the CELL-AVERAGE bed jump, so small high-order
    # wiggles receive only TVB limiting, while the actual Exner shock receives
    # the monotone P0 FV update.
    bbar = avg[:, 2]
    bpad = torch.cat((bbar[:1], bbar, bbar[-1:]))
    bed_jump = torch.maximum(
        torch.abs(bbar - bpad[:-2]),
        torch.abs(bpad[2:] - bbar),
    )
    strong_raw = bed_jump > B_FV_JUMP_THRESHOLD
    strong = _dilate_mask(strong_raw, FV_FALLBACK_BUFFER) if USE_FV_FALLBACK else torch.zeros_like(strong_raw)
    mild = troubled & (~strong)
    return mild, strong, comp_troubled


def apply_tvb_limiter(modal: torch.Tensor, mild: torch.Tensor) -> Tuple[torch.Tensor, int]:
    """
    Classical TVB modified-minmod on all variables (eta,q,b), with one common
    troubled-cell mask. Cell averages are conserved. For a P2 polynomial, the
    quadratic mode is removed in a mildly troubled cell.
    """
    if modal.shape[-1] <= 1 or not torch.any(mild):
        return modal, 0

    out = modal.clone()
    avg = out[:, :, 0]
    avg_pad = torch.cat((avg[:1], avg, avg[-1:]), dim=0)
    dm = avg - avg_pad[:-2]
    dp = avg_pad[2:] - avg

    a1 = out[:, :, 1]
    mm = minmod3(a1, MINMOD_BETA * dm, MINMOD_BETA * dp)

    # TVB modification: keep a small smooth slope even if minmod would alter it.
    keep = torch.abs(a1) <= (TVB_M * dx_global_for_limiter * dx_global_for_limiter)
    limited_a1 = torch.where(keep, a1, mm)
    out[mild, :, 1] = limited_a1[mild]
    if out.shape[-1] >= 3:
        out[mild, :, 2:] = 0.0
    return out, int(mild.sum().item())


def first_order_fv_integrated_flux(modal_old: torch.Tensor, dt: float):
    """
    First-order hydrostatic/Rusanov + upwind-Grass interface fluxes evaluated
    from OLD cell averages and integrated over one time step.
    """
    avg = modal_old[:, :, 0]
    N = avg.shape[0]
    UL = torch.empty((N + 1, 3), dtype=DTYPE, device=DEVICE)
    UR = torch.empty_like(UL)
    UL[1:N] = avg[:-1]
    UR[1:N] = avg[1:]
    UL[0] = avg[0]
    UR[0] = avg[0]
    UL[N] = avg[-1]
    UR[N] = avg[-1]
    FL, FR = interface_prebalanced_flux(UL, UR)
    return dt * FL, dt * FR


def hybridize_with_fv_fallback(
    modal_old: torch.Tensor,
    trial_high: torch.Tensor,
    Fhat_high_L: torch.Tensor,
    Fhat_high_R: torch.Tensor,
    strong: torch.Tensor,
    dx: float,
    dt: float,
) -> torch.Tensor:
    """
    Replace the high-order interface flux by the monotone first-order FV flux
    at every interface touching a strong cell. The flux correction is applied
    to ALL DG modes of neighboring cells, so the transition is conservative in
    eta and b. Strong cells themselves are then replaced by the exact P0 FV
    update (all higher modes set to zero).
    """
    if not USE_FV_FALLBACK or not torch.any(strong):
        return trial_high

    N, _, kp1 = modal_old.shape
    k = kp1 - 1
    Pminus, Pplus = legendre_at_endpoints(k)
    Fhat_fv_L, Fhat_fv_R = first_order_fv_integrated_flux(modal_old, dt)

    iface = torch.zeros(N + 1, dtype=torch.bool, device=DEVICE)
    iface[1:N] = strong[:-1] | strong[1:]
    iface[0] = strong[0]
    iface[N] = strong[-1]

    out = trial_high.clone()
    dFL = torch.where(iface[:, None], Fhat_fv_L - Fhat_high_L, torch.zeros_like(Fhat_high_L))
    dFR = torch.where(iface[:, None], Fhat_fv_R - Fhat_high_R, torch.zeros_like(Fhat_high_R))

    # Correct every DG mode in cells adjacent to a switched interface.
    for ell in range(k + 1):
        M = dx / float(2 * ell + 1)
        out[:, :, ell] -= dFL[1:] * Pplus[ell] / M
        out[:, :, ell] += dFR[:-1] * Pminus[ell] / M

    # A strong cell is a genuine P0 FV fallback: use the OLD average plus the
    # first-order side-dependent hydrostatic/Grass flux update.
    fv_avg = modal_old[:, :, 0] - (Fhat_fv_L[1:] - Fhat_fv_R[:-1]) / dx
    out[strong, :, 0] = fv_avg[strong]
    out[strong, :, 1:] = 0.0
    return out


def troubled_cell_limiter(modal: torch.Tensor, dx: float) -> Tuple[torch.Tensor, int]:
    """Compatibility wrapper: TVB-limit all detected non-strong cells."""
    global dx_global_for_limiter
    dx_global_for_limiter = dx
    mild, strong, _ = detect_troubled_cells(modal, dx)
    out, nmild = apply_tvb_limiter(modal, mild)
    if torch.any(strong):
        out[strong, :, 1:] = 0.0
    return out, nmild + int(strong.sum().item())


def positivity_scale(modal: torch.Tensor) -> Tuple[torch.Tensor, int]:
    """Scale nonconstant modes toward the cell average if h=eta-b gets small."""
    if modal.shape[-1] <= 1:
        hbar = modal[:, 0, 0] - modal[:, 2, 0]
        if torch.any(hbar <= H_FLOOR):
            raise FloatingPointError(f"Non-positive cell-average depth: {hbar.min().item():.3e}")
        return modal, 0

    hbar = modal[:, 0, 0] - modal[:, 2, 0]
    if torch.any(hbar <= H_FLOOR):
        raise FloatingPointError(f"Non-positive cell-average depth: {hbar.min().item():.3e}")

    xi = torch.linspace(-1.0, 1.0, 17, dtype=DTYPE, device=DEVICE)
    vals = evaluate_modal(modal, xi)
    h = vals[:, 0] - vals[:, 2]
    hmin = h.min(dim=1).values
    needs = hmin < H_FLOOR
    if not torch.any(needs):
        return modal, 0

    theta = torch.ones_like(hbar)
    theta[needs] = torch.clamp(
        (hbar[needs] - H_FLOOR) / (hbar[needs] - hmin[needs] + 1.0e-30),
        min=0.0,
        max=1.0,
    )
    out = modal.clone()
    out[:, :, 1:] *= theta[:, None, None]
    return out, int(needs.sum().item())


def compute_dt(modal: torch.Tensor, dx: float, t: float, tfinal: float) -> float:
    avg = modal[:, :, 0]
    h = (avg[:, 0] - avg[:, 2]).clamp_min(H_FLOOR)
    u = avg[:, 1] / h
    speed = torch.abs(u) + torch.sqrt(h) / FR
    amax = float(speed.max().item())
    dt = CFL_DG * dx / max(amax, 1.0e-14)
    return min(dt, tfinal - t)


