def series_mul(A: torch.Tensor, B: torch.Tensor, k: int, max_t: int) -> torch.Tensor:
    """
    Truncated 2D Taylor-series product in (x,t).
    A,B shape (N,k+1,k+1), indexed [cell,kx,kt].
    """
    C = torch.zeros_like(A)
    for total in range(k + 1):
        for kt in range(min(total, max_t) + 1):
            kx = total - kt
            if kx > k:
                continue
            val = torch.zeros(A.shape[0], dtype=DTYPE, device=DEVICE)
            for r in range(kx + 1):
                for s in range(kt + 1):
                    val = val + A[:, r, s] * B[:, kx - r, kt - s]
            C[:, kx, kt] = val
    return C


def series_inverse(H: torch.Tensor, k: int, max_t: int) -> torch.Tensor:
    """DT recursion for R=1/H, exactly as written in the notes."""
    R = torch.zeros_like(H)
    h00 = H[:, 0, 0]
    if torch.any(h00 <= H_FLOOR):
        raise FloatingPointError(f"Non-positive predictor-center depth: min={h00.min().item():.3e}")
    R[:, 0, 0] = 1.0 / h00

    for total in range(1, k + 1):
        for kt in range(min(total, max_t) + 1):
            kx = total - kt
            if kx > k:
                continue
            acc = torch.zeros(H.shape[0], dtype=DTYPE, device=DEVICE)
            for r in range(kx + 1):
                for s in range(kt + 1):
                    if r == 0 and s == 0:
                        continue
                    acc = acc + H[:, r, s] * R[:, kx - r, kt - s]
            R[:, kx, kt] = -acc / h00
    return R


def transformed_flux_source(Uc: torch.Tensor, k: int, max_t: int) -> Tuple[torch.Tensor, torch.Tensor, dict]:
    """
    Construct F_tilde and S_tilde from equation (12) and all intermediate
    transformed quantities Q1,Q2,G1,...,G4.

    Uc shape: (N,3,k+1,k+1) with variable order eta,q,b.
    """
    eta = Uc[:, 0]
    q = Uc[:, 1]
    b = Uc[:, 2]
    h = eta - b

    R = series_inverse(h, k, max_t)
    u = series_mul(q, R, k, max_t)
    u2 = series_mul(u, u, k, max_t)
    u3 = series_mul(u2, u, k, max_t)

    Q2 = (XI * A_GRASS) * u3
    Q1 = q + Q2

    G1 = series_mul(q, u, k, max_t)
    eta2 = series_mul(eta, eta, k, max_t)
    etab = series_mul(eta, b, k, max_t)
    G2 = 0.5 * INV_FR2 * eta2
    G3 = INV_FR2 * etab

    bx = torch.zeros_like(b)
    for kt in range(max_t + 1):
        for kx in range(k):
            if kx + kt <= k - 1:
                bx[:, kx, kt] = (kx + 1) * b[:, kx + 1, kt]
    etabx = series_mul(eta, bx, k, max_t)
    G4 = INV_FR2 * etabx

    F = torch.zeros_like(Uc)
    S = torch.zeros_like(Uc)
    F[:, 0] = Q1
    F[:, 1] = G1 + G2 - G3
    F[:, 2] = Q2
    S[:, 1] = -G4

    aux = {
        "h": h,
        "R": R,
        "u": u,
        "u2": u2,
        "Q1": Q1,
        "Q2": Q2,
        "G1": G1,
        "G2": G2,
        "G3": G3,
        "G4": G4,
        "bx": bx,
    }
    return F, S, aux


def local_space_time_predictor(modal: torch.Tensor, dx: float) -> Tuple[torch.Tensor, torch.Tensor, torch.Tensor]:
    """Build U_tilde, F_tilde, S_tilde in every cell via (11)--(12)."""
    N, _, kp1 = modal.shape
    k = kp1 - 1
    Uc = torch.zeros((N, 3, k + 1, k + 1), dtype=DTYPE, device=DEVICE)
    Uc[:, :, :, 0] = modal_to_spatial_taylor(modal, dx)

    # Successively increase temporal order, exactly following (11).
    for kt in range(k):
        F, S, _ = transformed_flux_source(Uc, k, max_t=kt)
        for kx in range(k - kt):
            Uc[:, :, kx, kt + 1] = (
                -float(kx + 1) / float(kt + 1) * F[:, :, kx + 1, kt]
                + 1.0 / float(kt + 1) * S[:, :, kx, kt]
            )

    F, S, _ = transformed_flux_source(Uc, k, max_t=k)
    return Uc, F, S


def eval_series(C: torch.Tensor, z: torch.Tensor, tloc: torch.Tensor, k: int) -> torch.Tensor:
    """
    Evaluate C(kx,kt) z^kx t^kt.
    C shape (N,3,k+1,k+1).
    z and tloc are broadcastable tensors. The common use below is scalar z/t
    or vectors handled one point at a time.
    """
    out = torch.zeros((C.shape[0], 3), dtype=DTYPE, device=DEVICE)
    for kt in range(k + 1):
        for kx in range(k - kt + 1):
            out = out + C[:, :, kx, kt] * (z ** kx) * (tloc ** kt)
    return out


