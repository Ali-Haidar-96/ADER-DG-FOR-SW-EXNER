    lim1, lim2, lim3 = limits(first), limits(q_hist), limits(third)

    frames=[]
    for i in idxs:
        fig=plt.figure(figsize=(9.2,8.4))
        a1=fig.add_axes([.11,.69,.84,.23]); a2=fig.add_axes([.11,.39,.84,.23]); a3=fig.add_axes([.11,.09,.84,.23])
        a1.plot(x, first[i], lw=2); a2.plot(x, q_hist[i], lw=2); a3.plot(x, third[i], lw=2)
        a1.set_ylabel(labels[0]); a2.set_ylabel(labels[1]); a3.set_ylabel(labels[2]); a3.set_xlabel("x [m]")
        for a in (a1,a2,a3):
            a.set_xlim(XMIN_PHYS,XMAX_PHYS); a.grid(True,alpha=.25)
            if BENCHMARK == "smooth":
                a.axvline(PHYSICAL_XMIN,ls="--",lw=1); a.axvline(PHYSICAL_XMAX,ls="--",lw=1)
        a1.set_ylim(*lim1); a2.set_ylim(*lim2); a3.set_ylim(*lim3)
        fig.suptitle(f"{BENCHMARK_TITLE} — P{POLY_DEGREE} ADER-DG ({STABILIZATION_MODE}), t={times[i]:.2f} s", fontsize=12.5, y=.975)
        fig.text(.5,.945,title_extra,ha="center",fontsize=9)
        buf=io.BytesIO(); fig.savefig(buf,format="png",dpi=105); plt.close(fig); buf.seek(0)
        frames.append(Image.open(buf).convert("P",palette=Image.Palette.ADAPTIVE))
    fs=frames+[frames[-1]]*GIF_FINAL_HOLD_FRAMES
    fs[0].save(GIF_PATH,save_all=True,append_images=fs[1:],duration=GIF_FRAME_DURATION_MS,loop=0,optimize=False)
