"""
ADER--DG solver in PyTorch for the 1D low-Froude shallow-water--Exner system.

This file implements the algorithm written in ADER_DG_Exner_Low_Froude.tex:

    U = (eta, q, b)^T,
    h = eta-b,
    u = q/h,

    U_t + F(U)_x = S,

    F(U) = ( q+q_b,
             q*u + (eta^2-2*eta*b)/(2 Fr^2),
             q_b )^T,

    S = (0, -eta*b_x/Fr^2, 0)^T,

    q_b = xi*A*u^3,  xi=1/(1-rho0).

The local space--time predictor is the triangular Taylor polynomial

    U_tau(x,t) = sum_{kt=0}^k sum_{kx=0}^{k-kt}
                 U_tilde(kx,kt) (x-x_j)^kx (t-t^n)^kt,

and its coefficients are generated by the differential-transformation (DT)
recurrence from the notes:

    U_tilde(kx,kt+1)
      = -(kx+1)/(kt+1) F_tilde(kx+1,kt)
        + 1/(kt+1) S_tilde(kx,kt).                         (11)

F_tilde and S_tilde are assembled exactly from the DT product/inverse rules
and the G1,...,G4 / Q1,Q2 decomposition in equation (12) of the notes.

The one-stage DG correction is then performed with time-dependent predictor
traces at cell interfaces. A hydrostatic reconstruction is used for the water
part of the numerical flux. The hydrostatic momentum flux is transformed to
THE PRE-BALANCED FLUX USED IN THE NOTES by subtracting b^2/(2 Fr^2) on the
corresponding side of each interface. This gives exact lake-at-rest balance
for piecewise constant topography and is consistent with the interior
pre-balanced flux/source pair.

For discontinuous benchmark data, a two-level stabilization is used. Mildly
troubled cells receive a classical TVB modified-minmod limiter applied jointly
to (eta,q,b). Strongly troubled cells, especially around the sharp Exner bed
shock, receive a conservative first-order hydrostatic/Rusanov + Grass finite-
volume fallback. Interfaces touching a fallback cell are switched consistently
for both neighboring cells. A positivity scaling limiter is applied afterward
if necessary.

Default benchmark
-----------------
Siviglia, Vanzo & Toro (2022), Riemann Test 1, with the same dimensional data
as the previously supplied finite-volume reference code. The data are first
nondimensionalized, so replacing gravity by 1/Fr^2 is dimensionally correct.

Default ADER--DG settings
-------------------------
Polynomial degree k = 2.
CFL = 0.18 (the value used for 1D k=2 experiments in the DT-ADER-DG SWE paper).
200 cells and T=2 s (benchmark values).

Outputs
-------
ader_dg_sw_exner_solution.csv
ader_dg_sw_exner_solution.pt
ader_dg_vs_reference.png
ader_dg_validation.txt
ADER_DG_SW_Exner_h_q_b_MONOTONE_BED_paper_variables.gif

The animation is generated from snapshots recorded during the SAME adaptive
ADER--DG run; the PDE is not rerun only for the GIF.

Requires: torch, numpy, matplotlib, pillow.
"""

