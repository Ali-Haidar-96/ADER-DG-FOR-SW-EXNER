def grass_flux(u: torch.Tensor) -> torch.Tensor:
    return XI * A_GRASS * u * torch.abs(u).pow(M_GRASS - 1)


def initial_state_nd(x: torch.Tensor) -> torch.Tensor:
    """Return U=(eta,q,total-bed) for the selected benchmark, nondimensional."""
    if BENCHMARK == "discontinuous":
        left = x < 0.0
        hL = H_LEFT_PHYS / H_REF
        qL = Q_LEFT_PHYS / Q_REF
        bL = B_LEFT_PHYS / H_REF
        hR = H_RIGHT_PHYS / H_REF
        qR = Q_RIGHT_PHYS / Q_REF
        bR = B_RIGHT_PHYS / H_REF
        h = torch.where(left, torch.full_like(x, hL), torch.full_like(x, hR))
        q = torch.where(left, torch.full_like(x, qL), torch.full_like(x, qR))
        b = torch.where(left, torch.full_like(x, bL), torch.full_like(x, bR))
        eta = h + b
        return torch.stack((eta, q, b), dim=1)

    # Smooth Figure-8 benchmark.  The third numerical component is TOTAL bed
    # B = b_fixed + z_b, because the shallow-water source depends on total bed.
    xp = x * L_REF
    eta = torch.full_like(xp, SMOOTH_ETA0 / H_REF)
    q = torch.full_like(xp, SMOOTH_Q0 / Q_REF)
    zb = 0.1 + 2.0 * torch.exp(-(xp ** 8) / 1.0e14)
    Btotal = (B_FIXED_PHYS + zb) / H_REF
    return torch.stack((eta, q, Btotal), dim=1)


def project_initial_condition(x_centers: torch.Tensor, dx: float, k: int) -> torch.Tensor:
    """Componentwise L2 projection onto Legendre P^k in every cell."""
    xi, w = gauss_legendre(max(k + 2, 4))
    P = legendre_values(k, xi)
    xq = x_centers[:, None] + 0.5 * dx * xi[None, :]
    Uq = initial_state_nd(xq.reshape(-1)).reshape(x_centers.numel(), xi.numel(), 3).permute(0, 2, 1)

    modal = torch.zeros((x_centers.numel(), 3, k + 1), dtype=DTYPE, device=DEVICE)
    for ell in range(k + 1):
        # a_l = (2l+1)/2 * integral_{-1}^1 U P_l dxi
        modal[:, :, ell] = 0.5 * (2 * ell + 1) * torch.sum(
            Uq * (w * P[ell])[None, None, :], dim=-1
        )
    return modal




def _smooth_sponge_gamma(x_phys: torch.Tensor) -> torch.Tensor:
    """Cubic sponge weight: one in [-200,200], smoothly decays to zero outside."""
    gamma = torch.ones_like(x_phys)
    if BENCHMARK != "smooth" or SPONGE_WIDTH <= 0.0:
        return gamma
    right = x_phys > PHYSICAL_XMAX
    left = x_phys < PHYSICAL_XMIN
    phi_r = torch.clamp((x_phys - PHYSICAL_XMAX) / SPONGE_WIDTH, 0.0, 1.0)
    phi_l = torch.clamp((PHYSICAL_XMIN - x_phys) / SPONGE_WIDTH, 0.0, 1.0)
    gr = -2.0 * (1.0 - phi_r) ** 3 + 3.0 * (1.0 - phi_r) ** 2
    gl = -2.0 * (1.0 - phi_l) ** 3 + 3.0 * (1.0 - phi_l) ** 2
    gamma = torch.where(right, gr, gamma)
    gamma = torch.where(left, gl, gamma)
    return gamma


def apply_benchmark_boundary_treatment(modal: torch.Tensor, x_nd: torch.Tensor) -> torch.Tensor:
    """No-op for the Riemann test; sponge relaxation for the smooth Figure-8 test."""
    if BENCHMARK != "smooth":
        return modal
    xp = x_nd * L_REF
    G = _smooth_sponge_gamma(xp)
    equilibrium = torch.tensor([
        SMOOTH_ETA0 / H_REF,
        SMOOTH_Q0 / Q_REF,
        (B_FIXED_PHYS + 0.1) / H_REF,
    ], dtype=DTYPE, device=DEVICE)
    out = modal.clone()
    out[:, :, 0] = G[:, None] * out[:, :, 0] + (1.0 - G[:, None]) * equilibrium[None, :]
    if out.shape[-1] > 1:
        out[:, :, 1:] = G[:, None, None] * out[:, :, 1:]
    return out

