@dataclass
class DGSolution:
    x_nd: torch.Tensor
    modal_initial: torch.Tensor
    modal_final: torch.Tensor
    time_nd: float
    nsteps: int
    dt_min_phys: float
    dt_max_phys: float
    dt_mean_phys: float
    total_troubled: int
    total_positivity_scaled: int
    wall_seconds: float

    # Cell-average snapshots from the SAME adaptive ADER--DG trajectory.
    # Shapes:
    #   snapshot_times_phys : (nsnap,)
    #   snapshot_eta_phys   : (nsnap, N_ELEMS)
    #   snapshot_q_phys     : (nsnap, N_ELEMS)
    #   snapshot_b_phys     : (nsnap, N_ELEMS)
    snapshot_times_phys: np.ndarray
    snapshot_eta_phys: np.ndarray
    snapshot_q_phys: np.ndarray
    snapshot_b_phys: np.ndarray

    @property
    def avg(self):
        return self.modal_final[:, :, 0]

    @property
    def eta_phys(self):
        return self.avg[:, 0] * H_REF

    @property
    def q_phys(self):
        return self.avg[:, 1] * Q_REF

    @property
    def b_phys(self):
        return self.avg[:, 2] * H_REF

    @property
    def h_phys(self):
        return (self.avg[:, 0] - self.avg[:, 2]) * H_REF

    @property
    def x_phys(self):
        return self.x_nd * L_REF


def run_ader_dg(verbose: bool = True) -> DGSolution:
    global dx_global_for_limiter
    xmin = XMIN_PHYS / L_REF
    xmax = XMAX_PHYS / L_REF
    dx = (xmax - xmin) / N_ELEMS
    x = torch.linspace(xmin + 0.5 * dx, xmax - 0.5 * dx, N_ELEMS, dtype=DTYPE, device=DEVICE)
    modal = project_initial_condition(x, dx, POLY_DEGREE)
    modal0 = modal.clone()

    tfinal = TFINAL_PHYS / T_REF
    t = 0.0
    nsteps = 0
    dts = []
    total_troubled = 0
    total_pos = 0

    # Record the initial cell averages. These histories are used only for
    # visualization and do not feed back into the solver.
    snapshot_times_phys = [0.0]
    snapshot_eta_phys = [(modal[:, 0, 0] * H_REF).detach().cpu().numpy().copy()]
    snapshot_q_phys = [(modal[:, 1, 0] * Q_REF).detach().cpu().numpy().copy()]
    snapshot_b_phys = [(modal[:, 2, 0] * H_REF).detach().cpu().numpy().copy()]

    t0 = time.perf_counter()

    while t < tfinal - 1.0e-15:
        if nsteps >= MAX_STEPS:
            raise RuntimeError("Exceeded MAX_STEPS")
        dt = compute_dt(modal, dx, t, tfinal)

        # Predictor (11)--(12).
        Uc, Fc, Sc = local_space_time_predictor(modal, dx)

        # One-stage high-order correction (7), retaining the time-integrated
        # high-order interface fluxes for the a-posteriori hybrid correction.
        trial_high, Fhat_high_L, Fhat_high_R = dg_one_stage_update(
            modal, Uc, Fc, Sc, dx, dt, return_fluxes=True
        )
        if not torch.isfinite(trial_high).all():
            raise FloatingPointError(f"Non-finite DG state at step {nsteps}, t={t*T_REF:.6e}s")

        # Detect on the candidate P2 solution. All variables eta,q,b enter the
        # detector. Strong cells receive a conservative P0 FV fallback; mild
        # cells receive the TVB modified-minmod limiter.
        dx_global_for_limiter = dx
        mild, strong, _ = detect_troubled_cells(trial_high, dx)
        trial = hybridize_with_fv_fallback(
            modal, trial_high, Fhat_high_L, Fhat_high_R, strong, dx, dt
        )
        trial, nmild = apply_tvb_limiter(trial, mild)
        nstrong = int(strong.sum().item())
        ntr = nmild + nstrong
        trial, npos = positivity_scale(trial)
        trial = apply_benchmark_boundary_treatment(trial, x)

        modal = trial
        t += dt
        nsteps += 1
        dts.append(dt * T_REF)
        total_troubled += ntr
        total_pos += npos

        # Save the accepted state after this adaptive ADER--DG step.
        snapshot_times_phys.append(t * T_REF)
        snapshot_eta_phys.append((modal[:, 0, 0] * H_REF).detach().cpu().numpy().copy())
        snapshot_q_phys.append((modal[:, 1, 0] * Q_REF).detach().cpu().numpy().copy())
        snapshot_b_phys.append((modal[:, 2, 0] * H_REF).detach().cpu().numpy().copy())

        if verbose and (nsteps % 100 == 0 or t >= tfinal - 1e-15):
            avg = modal[:, :, 0]
            hmin = float((avg[:, 0] - avg[:, 2]).min().item()) * H_REF
            print(
                f"step={nsteps:5d}  t={t*T_REF:10.6f}s  dt={dt*T_REF:.3e}s  "
                f"min(hbar)={hmin:.6e}m  TVB={nmild}  FV={nstrong}"
            )

    wall = time.perf_counter() - t0
    return DGSolution(
        x_nd=x,
        modal_initial=modal0,
        modal_final=modal,
        time_nd=t,
        nsteps=nsteps,
        dt_min_phys=min(dts),
        dt_max_phys=max(dts),
        dt_mean_phys=sum(dts) / len(dts),
        total_troubled=total_troubled,
        total_positivity_scaled=total_pos,
        wall_seconds=wall,
        snapshot_times_phys=np.asarray(snapshot_times_phys),
        snapshot_eta_phys=np.asarray(snapshot_eta_phys),
        snapshot_q_phys=np.asarray(snapshot_q_phys),
        snapshot_b_phys=np.asarray(snapshot_b_phys),
    )


def lake_at_rest_residual_test() -> Tuple[float, float, float]:
    """
    One-step DG check for q=0, eta=constant, discontinuous b. Report max
    change in cell averages divided by dt. Uses degree 0 deliberately so the
    discontinuous-bed balance is tested without polynomial projection artifacts.
    """
    xmin = XMIN_PHYS / L_REF
    xmax = XMAX_PHYS / L_REF
    dx = (xmax - xmin) / N_ELEMS
    x = torch.linspace(xmin + 0.5 * dx, xmax - 0.5 * dx, N_ELEMS, dtype=DTYPE, device=DEVICE)

    k = 0
    modal = torch.zeros((N_ELEMS, 3, 1), dtype=DTYPE, device=DEVICE)
    bL = B_LEFT_PHYS / H_REF
    bR = B_RIGHT_PHYS / H_REF
    b = torch.where(x < 0.0, torch.full_like(x, bL), torch.full_like(x, bR))
    eta = torch.full_like(x, 2.5)
    modal[:, 0, 0] = eta
    modal[:, 1, 0] = 0.0
    modal[:, 2, 0] = b

    # Build degree-0 predictor directly.
    Uc = torch.zeros((N_ELEMS, 3, 1, 1), dtype=DTYPE, device=DEVICE)
    Uc[:, :, 0, 0] = modal[:, :, 0]
    Fc, Sc, _ = transformed_flux_source(Uc, k=0, max_t=0)
    dt = 1.0e-6

    # Local degree-0 update specialized from dg_one_stage_update to avoid using
    # global POLY_DEGREE quadrature assumptions.
    cell_left = Uc[:, :, 0, 0]
    cell_right = cell_left
    UL, UR = all_interface_states(cell_left, cell_right)
    FL, FR = interface_prebalanced_flux(UL, UR)

    newavg = modal[:, :, 0].clone()
    newavg -= (dt / dx) * (FL[1:] - FR[:-1])
    # Source is zero in each piecewise-constant cell; interface correction
    # accounts for the bed jump.
    residual = (newavg - modal[:, :, 0]) / dt
    return tuple(float(residual[:, i].abs().max().item()) for i in range(3))


def dt_identity_test(modal: torch.Tensor, dx: float) -> float:
    """
    Internal algebra check: after building the predictor, verify recurrence
    (11) at every coefficient. Returns max absolute coefficient residual.
    """
    Uc, Fc, Sc = local_space_time_predictor(modal, dx)
    k = modal.shape[-1] - 1
    rmax = 0.0
    for kt in range(k):
        for kx in range(k - kt):
            lhs = Uc[:, :, kx, kt + 1]
            rhs = -(kx + 1) / (kt + 1) * Fc[:, :, kx + 1, kt] + Sc[:, :, kx, kt] / (kt + 1)
            rmax = max(rmax, float((lhs - rhs).abs().max().item()))
    return rmax


