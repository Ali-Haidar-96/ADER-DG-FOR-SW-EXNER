def save_animation(sol: DGSolution, gif_path: Path = GIF_PATH) -> Path:
    """
    Create an animated GIF of h(x,t), q(x,t), and the moving bed b(x,t), matching the variables shown in the published benchmark.

    Important:
      * The frames come from snapshots recorded during the SAME adaptive
        ADER--DG run used for the final numerical solution.
      * No artificial animation time step is imposed.
      * The x/y axes are fixed over all frames so that apparent motion is
        physical/numerical evolution rather than axis rescaling.
    """
    times = sol.snapshot_times_phys
    eta_hist = sol.snapshot_eta_phys
    q_hist = sol.snapshot_q_phys
    b_hist = sol.snapshot_b_phys
    h_hist = eta_hist - b_hist
    x_phys = sol.x_phys.detach().cpu().numpy()

    if len(times) < 2:
        raise RuntimeError("Not enough snapshots to build the animation")

    # Choose approximately evenly spaced PHYSICAL times, then use the nearest
    # state from the already recorded adaptive-time trajectory.
    target_times = np.linspace(0.0, TFINAL_PHYS, N_ANIMATION_FRAMES)
    frame_indices = np.unique(
        [int(np.argmin(np.abs(times - tt))) for tt in target_times]
    )
    frame_indices = np.unique(
        np.concatenate(([0], frame_indices, [len(times) - 1]))
    )

    def padded_limits(a: np.ndarray, frac: float = 0.07):
        amin = float(np.min(a))
        amax = float(np.max(a))
        span = amax - amin
        if span == 0.0:
            span = max(abs(amin), 1.0)
        return amin - frac * span, amax + frac * span

    h_lim = padded_limits(h_hist)
    q_lim = padded_limits(q_hist)
    b_lim = padded_limits(b_hist)

    frames = []

    for idx in frame_indices:
        fig = plt.figure(figsize=(9.2, 8.4))

        ax1 = fig.add_axes([0.11, 0.69, 0.84, 0.23])
        ax2 = fig.add_axes([0.11, 0.39, 0.84, 0.23])
        ax3 = fig.add_axes([0.11, 0.09, 0.84, 0.23])

        ax1.plot(x_phys, h_hist[idx], linewidth=2)
        ax2.plot(x_phys, q_hist[idx], linewidth=2)
        ax3.plot(x_phys, b_hist[idx], linewidth=2)

        ax1.set_ylabel(r"$h$ [m]")
        ax2.set_ylabel(r"$q$ [m$^2$/s]")
        ax3.set_ylabel(r"$b$ [m]")
        ax3.set_xlabel(r"$x$ [m]")

        for ax in (ax1, ax2, ax3):
            ax.set_xlim(XMIN_PHYS, XMAX_PHYS)
            ax.grid(True, alpha=0.25)

        ax1.set_ylim(*h_lim)
        ax2.set_ylim(*q_lim)
        ax3.set_ylim(*b_lim)

        fig.suptitle(
            f"1D low-Froude SW--Exner -- P{POLY_DEGREE} ADER--DG, "
            f"N = {N_ELEMS}, t = {times[idx]:.3f} s",
            fontsize=13,
            y=0.975,
        )
        fig.text(
            0.5,
            0.945,
            "Siviglia--Vanzo--Toro Riemann Test 1 | "
            "variables shown as h, q, b | Grass sediment transport | moving bed",
            ha="center",
            va="center",
            fontsize=9,
        )

        buf = io.BytesIO()
        fig.savefig(buf, format="png", dpi=105)
        plt.close(fig)
        buf.seek(0)

        # Convert each PNG to an indexed palette suitable for a GIF.
        frames.append(
            Image.open(buf).convert("P", palette=Image.Palette.ADAPTIVE)
        )

    # Hold the final state slightly longer.
    frames_to_save = frames + [frames[-1]] * GIF_FINAL_HOLD_FRAMES
    frames_to_save[0].save(
        gif_path,
        save_all=True,
        append_images=frames_to_save[1:],
        duration=GIF_FRAME_DURATION_MS,
        loop=0,
        optimize=False,
    )

    return gif_path




def install_fast_p2_kernels():
    """Install algebraically identical optimized P2 kernels for long runs."""
    global modal_to_spatial_taylor, dg_one_stage_update
    if POLY_DEGREE != 2:
        return

    xi_q, wx_q = gauss_legendre(NQ_SPACE)
    th_q, wt_q = gauss_legendre(NQ_TIME, 0.0, 1.0)
    P_q = legendre_values(POLY_DEGREE, xi_q)
    DP_q = legendre_derivative_values(POLY_DEGREE, xi_q)
    Pminus, Pplus = legendre_at_endpoints(POLY_DEGREE)

    def fast_modal_to_spatial_taylor(modal, dx):
        out = torch.zeros_like(modal)
        out[:, :, 0] = modal[:, :, 0] - 0.5 * modal[:, :, 2]
        out[:, :, 1] = (2.0 / dx) * modal[:, :, 1]
        out[:, :, 2] = (6.0 / (dx * dx)) * modal[:, :, 2]
        return out

    def eval_series_grid(C, zvals, tvals):
        zpow = torch.stack([zvals ** a for a in range(3)], dim=1)
        tpow = torch.stack([tvals ** b for b in range(3)], dim=1)
        return torch.einsum('nvab,xa,tb->nvtx', C, zpow, tpow)

    def fast_dg_one_stage_update(modal, Uc, Fc, Sc, dx, dt, return_fluxes=False):
        N = modal.shape[0]
        zq = 0.5 * dx * xi_q
        tq = dt * th_q
        Fvals = eval_series_grid(Fc, zq, tq)
        Svals = eval_series_grid(Sc, zq, tq)
        vol = dt * torch.einsum('nvtx,t,x,lx->nvl', Fvals, wt_q, wx_q, DP_q)
        src = dt * (0.5 * dx) * torch.einsum('nvtx,t,x,lx->nvl', Svals, wt_q, wx_q, P_q)

        zends = torch.tensor([-0.5 * dx, 0.5 * dx], dtype=DTYPE, device=DEVICE)
        Uends = eval_series_grid(Uc, zends, tq)
        cleft = Uends[:, :, :, 0].permute(2, 0, 1)
        cright = Uends[:, :, :, 1].permute(2, 0, 1)
        nt = tq.numel()
        UL = torch.empty((nt, N + 1, 3), dtype=DTYPE, device=DEVICE)
        UR = torch.empty_like(UL)
        UL[:, 1:N, :] = cright[:, :-1, :]
        UR[:, 1:N, :] = cleft[:, 1:, :]
        UL[:, 0, :] = cleft[:, 0, :]
        UR[:, 0, :] = cleft[:, 0, :]
        UL[:, N, :] = cright[:, -1, :]
        UR[:, N, :] = cright[:, -1, :]

        FLflat, FRflat = interface_prebalanced_flux(UL.reshape(-1, 3), UR.reshape(-1, 3))
        FL = FLflat.reshape(nt, N + 1, 3)
        FR = FRflat.reshape(nt, N + 1, 3)
        FhatL = dt * torch.einsum('t,tiv->iv', wt_q, FL)
        FhatR = dt * torch.einsum('t,tiv->iv', wt_q, FR)

        masses = torch.tensor([dx / float(2 * ell + 1) for ell in range(3)], dtype=DTYPE, device=DEVICE)
        rhs = masses[None, None, :] * modal + vol + src
        rhs -= FhatL[1:, :, None] * Pplus[None, None, :]
        rhs += FhatR[:-1, :, None] * Pminus[None, None, :]
        new = rhs / masses[None, None, :]
        if return_fluxes:
            return new, FhatL, FhatR
        return new

    modal_to_spatial_taylor = fast_modal_to_spatial_taylor
    dg_one_stage_update = fast_dg_one_stage_update

