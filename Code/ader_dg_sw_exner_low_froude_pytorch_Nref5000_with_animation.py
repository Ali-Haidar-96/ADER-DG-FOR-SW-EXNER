def rusanov_hydro_flux(hL: torch.Tensor, qL: torch.Tensor, hR: torch.Tensor, qR: torch.Tensor):
    hLs = hL.clamp_min(H_FLOOR)
    hRs = hR.clamp_min(H_FLOOR)
    uL = qL / hLs
    uR = qR / hRs

    FL = torch.stack((qL, qL * uL + 0.5 * INV_FR2 * hL * hL), dim=-1)
    FRv = torch.stack((qR, qR * uR + 0.5 * INV_FR2 * hR * hR), dim=-1)
    a = torch.maximum(torch.abs(uL) + torch.sqrt(hLs) / FR,
                      torch.abs(uR) + torch.sqrt(hRs) / FR)
    jump = torch.stack((hR - hL, qR - qL), dim=-1)
    return 0.5 * (FL + FRv) - 0.5 * a[:, None] * jump


def interface_prebalanced_flux(UL: torch.Tensor, UR: torch.Tensor) -> Tuple[torch.Tensor, torch.Tensor]:
    """
    Hydrostatic reconstruction at all interfaces.

    UL,UR shape (Ninterfaces,3), variables (eta,q,b).

    Returns two fluxes because hydrostatic source corrections are cell-side
    dependent:
      F_for_left_cell  -- used at the right boundary of the cell on the left,
      F_for_right_cell -- used at the left boundary of the cell on the right.

    The momentum component is transformed from the standard h-form to the
    pre-balanced flux of the notes via -b_side^2/(2 Fr^2).
    """
    etaL, qL, bL = UL[:, 0], UL[:, 1], UL[:, 2]
    etaR, qR, bR = UR[:, 0], UR[:, 1], UR[:, 2]
    hL = etaL - bL
    hR = etaR - bR

    if torch.any(hL <= 0.0) or torch.any(hR <= 0.0):
        raise FloatingPointError(
            f"Non-positive interface depth: minL={hL.min().item():.3e}, minR={hR.min().item():.3e}"
        )

    bstar = torch.maximum(bL, bR)
    hLstar = torch.clamp(etaL - bstar, min=0.0)
    hRstar = torch.clamp(etaR - bstar, min=0.0)

    ratioL = torch.where(hL > H_FLOOR, hLstar / hL, torch.zeros_like(hL))
    ratioR = torch.where(hR > H_FLOOR, hRstar / hR, torch.zeros_like(hR))
    qLstar = qL * ratioL
    qRstar = qR * ratioR

    Fstar = rusanov_hydro_flux(hLstar, qLstar, hRstar, qRstar)

    corrL = 0.5 * INV_FR2 * (hL * hL - hLstar * hLstar)
    corrR = 0.5 * INV_FR2 * (hR * hR - hRstar * hRstar)
    Fstd_mom_L = Fstar[:, 1] + corrL
    Fstd_mom_R = Fstar[:, 1] + corrR

    # Transform standard momentum flux to the pre-balanced momentum flux.
    Fpre_mom_L = Fstd_mom_L - 0.5 * INV_FR2 * bL * bL
    Fpre_mom_R = Fstd_mom_R - 0.5 * INV_FR2 * bR * bR

    uL = qL / hL.clamp_min(H_FLOOR)
    uR = qR / hR.clamp_min(H_FLOOR)
    qbL = grass_flux(uL)
    qbR = grass_flux(uR)
    qb = torch.where(Fstar[:, 0] >= 0.0, qbL, qbR)

    F_left = torch.stack((Fstar[:, 0] + qb, Fpre_mom_L, qb), dim=-1)
    F_right = torch.stack((Fstar[:, 0] + qb, Fpre_mom_R, qb), dim=-1)
    return F_left, F_right


def predictor_interface_states(Uc: torch.Tensor, dx: float, tloc: torch.Tensor) -> Tuple[torch.Tensor, torch.Tensor]:
    """Return each cell's left/right predictor trace at local time tloc."""
    k = Uc.shape[-1] - 1
    zL = torch.tensor(-0.5 * dx, dtype=DTYPE, device=DEVICE)
    zR = torch.tensor(+0.5 * dx, dtype=DTYPE, device=DEVICE)
    cell_left = eval_series(Uc, zL, tloc, k)
    cell_right = eval_series(Uc, zR, tloc, k)
    return cell_left, cell_right


def all_interface_states(cell_left: torch.Tensor, cell_right: torch.Tensor) -> Tuple[torch.Tensor, torch.Tensor]:
    """Transmissive boundaries; returns UL/UR for N+1 interfaces."""
    N = cell_left.shape[0]
    UL = torch.empty((N + 1, 3), dtype=DTYPE, device=DEVICE)
    UR = torch.empty((N + 1, 3), dtype=DTYPE, device=DEVICE)

    # Interior interfaces i=1,...,N-1: left cell i-1, right cell i.
    UL[1:N] = cell_right[:-1]
    UR[1:N] = cell_left[1:]

    # Transmissive boundaries.
    UL[0] = cell_left[0]
    UR[0] = cell_left[0]
    UL[N] = cell_right[-1]
    UR[N] = cell_right[-1]
    return UL, UR


