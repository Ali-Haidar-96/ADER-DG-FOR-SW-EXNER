def gauss_legendre(n: int, a: float = -1.0, b: float = 1.0) -> Tuple[torch.Tensor, torch.Tensor]:
    x, w = np.polynomial.legendre.leggauss(n)
    x = 0.5 * (b - a) * x + 0.5 * (a + b)
    w = 0.5 * (b - a) * w
    return (
        torch.tensor(x, dtype=DTYPE, device=DEVICE),
        torch.tensor(w, dtype=DTYPE, device=DEVICE),
    )


def legendre_values(k: int, xi: torch.Tensor) -> torch.Tensor:
    """Return P_l(xi), shape (k+1, nq)."""
    vals = []
    x_np = xi.detach().cpu().numpy()
    for ell in range(k + 1):
        c = np.zeros(ell + 1)
        c[-1] = 1.0
        vals.append(torch.tensor(np.polynomial.legendre.legval(x_np, c), dtype=DTYPE, device=DEVICE))
    return torch.stack(vals, dim=0)


def legendre_derivative_values(k: int, xi: torch.Tensor) -> torch.Tensor:
    """Return dP_l/dxi(xi), shape (k+1, nq)."""
    vals = []
    x_np = xi.detach().cpu().numpy()
    for ell in range(k + 1):
        c = np.zeros(ell + 1)
        c[-1] = 1.0
        dc = np.polynomial.legendre.legder(c)
        vals.append(torch.tensor(np.polynomial.legendre.legval(x_np, dc), dtype=DTYPE, device=DEVICE))
    return torch.stack(vals, dim=0)


def legendre_at_endpoints(k: int) -> Tuple[torch.Tensor, torch.Tensor]:
    p_plus = torch.ones(k + 1, dtype=DTYPE, device=DEVICE)
    p_minus = torch.tensor([(-1.0) ** ell for ell in range(k + 1)], dtype=DTYPE, device=DEVICE)
    return p_minus, p_plus


def modal_to_spatial_taylor(modal: torch.Tensor, dx: float) -> torch.Tensor:
    """
    Convert U_h = sum_l a_l P_l(xi), xi=2(x-xj)/dx, to the exact local
    spatial Taylor coefficients U_tilde(kx,0) from equation (10b).

    modal shape: (N, 3, k+1)
    returns:     (N, 3, k+1)
    """
    N, nvar, kp1 = modal.shape
    k = kp1 - 1
    out = torch.zeros_like(modal)
    for ell in range(k + 1):
        leg = np.zeros(ell + 1)
        leg[-1] = 1.0
        # Power coefficients of P_ell(xi): sum_r p_r xi^r.
        p = np.polynomial.legendre.leg2poly(leg)
        for r, coeff in enumerate(p):
            out[:, :, r] += modal[:, :, ell] * (float(coeff) * (2.0 / dx) ** r)
    return out


def evaluate_modal(modal: torch.Tensor, xi: torch.Tensor) -> torch.Tensor:
    """Evaluate modal polynomial. Output shape (N,3,nq)."""
    P = legendre_values(modal.shape[-1] - 1, xi)
    return torch.einsum("nvl,lq->nvq", modal, P)


