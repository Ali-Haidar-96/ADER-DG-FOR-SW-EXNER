def grass_flux(u: torch.Tensor) -> torch.Tensor:
    return XI * A_GRASS * u * torch.abs(u).pow(M_GRASS - 1)


def initial_state_nd(x: torch.Tensor) -> torch.Tensor:
    """Return U=(eta,q,b) for the published Riemann data, nondimensional."""
    left = x < 0.0

    hL = H_LEFT_PHYS / H_REF
    qL = Q_LEFT_PHYS / Q_REF
    bL = B_LEFT_PHYS / H_REF
    hR = H_RIGHT_PHYS / H_REF
    qR = Q_RIGHT_PHYS / Q_REF
    bR = B_RIGHT_PHYS / H_REF

    h = torch.where(left, torch.full_like(x, hL), torch.full_like(x, hR))
    q = torch.where(left, torch.full_like(x, qL), torch.full_like(x, qR))
    b = torch.where(left, torch.full_like(x, bL), torch.full_like(x, bR))
    eta = h + b
    return torch.stack((eta, q, b), dim=1)


def project_initial_condition(x_centers: torch.Tensor, dx: float, k: int) -> torch.Tensor:
    """Componentwise L2 projection onto Legendre P^k in every cell."""
    xi, w = gauss_legendre(max(k + 2, 4))
    P = legendre_values(k, xi)
    xq = x_centers[:, None] + 0.5 * dx * xi[None, :]
    Uq = initial_state_nd(xq.reshape(-1)).reshape(x_centers.numel(), xi.numel(), 3).permute(0, 2, 1)

    modal = torch.zeros((x_centers.numel(), 3, k + 1), dtype=DTYPE, device=DEVICE)
    for ell in range(k + 1):
        # a_l = (2l+1)/2 * integral_{-1}^1 U P_l dxi
        modal[:, :, ell] = 0.5 * (2 * ell + 1) * torch.sum(
            Uq * (w * P[ell])[None, None, :], dim=-1
        )
    return modal


